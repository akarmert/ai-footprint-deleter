import type { MediaScan } from './protocol';
import type { MetadataRecord } from './engine';

export const categories = [
  { id: 'c2pa', label: 'C2PA', title: 'Content Authenticity (C2PA)' },
  { id: 'file', label: 'File', title: 'File Information' },
  { id: 'other', label: 'Other', title: 'Other Metadata' },
  { id: 'privacy', label: 'Privacy', title: 'Privacy / Sensitive Metadata' },
  { id: 'color', label: 'Color / ICC', title: 'Color / ICC Information' },
  { id: 'production', label: 'Production', title: 'Production / Prompt Metadata' },
] as const;
export type Category = typeof categories[number]['id'];
export type ResultField = { id: string; label: string; value: string; category: Category; ai: boolean; record?: MetadataRecord };

export function aiEvidence(value: string): boolean {
  return /\btrainedAlgorithmicMedia\b|\b(?:AI[- ]generated|AI generation|generated by (?:AI|DALL[·-]?E|Midjourney|Stable Diffusion|ChatGPT)|stable diffusion|midjourney|comfyui|automatic1111|dall[·-]?e)\b|(?:^|[\s"'<:{,])(?:prompt|negative_prompt|sampler_name|cfg_scale)\s*["']?\s*[:=>]/i.test(value);
}

export function describeResults(scan: MediaScan, file: { name: string; size: number }) {
  const provenance = scan.c2pa !== 'not-detected-not-guaranteed';
  const fields: ResultField[] = [];
  const add = (id: string, label: string, value: string, category: Category) => fields.push({ id, label, value, category, ai: false });
  add('name', 'Dosya adı', file.name, 'file');
  add('size', 'Dosya boyutu', `${file.size.toLocaleString('tr-TR')} bayt`, 'file');
  add('format', 'File Type', scan.format, 'file');
  add('dimensions', 'Image Size / Width × Height', `${scan.width} × ${scan.height}`, 'file');
  add('megapixels', 'Megapixels', (scan.width * scan.height / 1000000).toLocaleString('tr-TR', { maximumFractionDigits: 3 }), 'file');
  add('orientation', 'Yön', scan.orientation === null ? 'Bilinmiyor' : String(scan.orientation), 'file');
  add('alpha', 'Alpha', scan.alpha ? 'Var' : 'Yok', 'file');
  if (provenance) add('c2pa-status', 'C2PA Status', scan.c2pa, 'c2pa');
  for (const record of scan.records) {
    const value = record.preview;
    const ai = aiEvidence(value);
    const category: Category = /c2pa|provenance|jumbf|jumd/i.test(record.kind) ? 'c2pa'
      : /ICC|color|cHRM|gAMA|sRGB|sBIT/i.test(record.kind) ? 'color'
      : ai || /\bprompt\b|negative_prompt|sampler_name|cfg_scale/i.test(value) ? 'production'
      : /exif|gps|iptc/i.test(record.kind) || /\b(?:copyright|creator|author|location|serialnumber|gps)\b/i.test(value) ? 'privacy' : 'other';
    fields.push({ id: `record-${record.id}`, label: record.kind, value, category, ai, record });
  }
  return { fields, provenance, aiCount: fields.filter(field => field.ai).length, sectionCount: categories.filter(category => fields.some(field => field.category === category.id)).length };
}
