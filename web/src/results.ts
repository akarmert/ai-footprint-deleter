import type { MediaScan } from './protocol';
import type { MetadataRecord } from './engine';
import { AI_DIGITAL_SOURCE_TERM_PATTERN, AI_DIGITAL_SOURCE_TYPE_URI_PATTERN } from './ai-source-types.ts';
import { describeAiTools, detectAiTools } from './ai-generator.ts';
import { formatBytes } from './app-state.ts';

export const categories = [
  { id: 'c2pa', label: 'C2PA kaydı' },
  { id: 'file', label: 'Dosya bilgileri' },
  { id: 'other', label: 'Diğer metadata' },
  { id: 'privacy', label: 'Kişisel veriler' },
  { id: 'color', label: 'Renk profili' },
  { id: 'production', label: 'AI ve üretim bilgisi' },
] as const;
export type Category = (typeof categories)[number]['id'];
export type ResultField = {
  id: string;
  label: string;
  value: string;
  category: Category;
  ai: boolean;
  record?: MetadataRecord;
};

const aiTermText = new RegExp(`\\b${AI_DIGITAL_SOURCE_TERM_PATTERN}\\b`, 'i');
const explicitDeclaration = new RegExp(
  `(?:[\\w.-]+:DigitalSourceType\\s*=\\s*["']${AI_DIGITAL_SOURCE_TYPE_URI_PATTERN}["']|<(?:[\\w.-]+:)?DigitalSourceType>\\s*${AI_DIGITAL_SOURCE_TYPE_URI_PATTERN}\\s*<\\/)`,
);

export function aiEvidence(value: string): boolean {
  return (
    aiTermText.test(value) ||
    /\b(?:AI[- ]generated|AI generation|generated by (?:AI|DALL[·-]?E|Midjourney|Stable Diffusion|ChatGPT)|stable diffusion|midjourney|comfyui|automatic1111|dall[·-]?e)\b|(?:^|[\s"'<:{,])(?:prompt|negative_prompt|sampler_name|cfg_scale)\s*["']?\s*[:=>]/i.test(
      value,
    )
  );
}

export function explicitTextDeclaration(value: string): boolean {
  return explicitDeclaration.test(value);
}

export function describeResults(scan: MediaScan, file: { name: string; size: number }) {
  const provenance =
    scan.c2pa !== 'not-detected-not-guaranteed' || (!!scan.provenance && scan.provenance.status !== 'absent');
  const fields: ResultField[] = [];
  const add = (id: string, label: string, value: string, category: Category) =>
    fields.push({ id, label, value, category, ai: false });
  add('name', 'Dosya adı', file.name, 'file');
  add('size', 'Dosya boyutu', formatBytes(file.size), 'file');
  add('format', 'File Type', scan.format, 'file');
  add('dimensions', 'Image Size', `${scan.width} × ${scan.height}`, 'file');
  add(
    'megapixels',
    'Megapixels',
    ((scan.width * scan.height) / 1000000).toLocaleString('tr-TR', { maximumFractionDigits: 3 }),
    'file',
  );
  add('orientation', 'Yön (EXIF)', scan.orientation === null ? 'Belirsiz' : String(scan.orientation), 'file');
  add('alpha', 'Saydamlık', scan.alpha ? 'Var' : 'Yok', 'file');
  const tools = describeAiTools(detectAiTools(scan));
  fields.push({
    id: 'ai-tool',
    label: 'AI aracı (beyan)',
    value: tools.found ? tools.detail : `${tools.headline}. ${tools.detail}`,
    category: 'file',
    ai: tools.found,
  });
  if (provenance) add('c2pa-status', 'C2PA Status', 'Var, doğrulanmadı', 'c2pa');
  for (const record of scan.records) {
    const value = record.preview;
    const structural = 'footprints' in scan ? scan.footprints : undefined;
    const ai = structural
      ? structural.evidence.some(
          e => e.recordId === record.id && (e.category === 'explicit-ai' || e.category === 'metadata-hint'),
        )
      : aiEvidence(value);
    const category: Category = /c2pa|provenance|jumbf|jumd/i.test(record.kind)
      ? 'c2pa'
      : /ICC|color|cHRM|gAMA|sRGB|sBIT/i.test(record.kind)
        ? 'color'
        : ai || /\bprompt\b|negative_prompt|sampler_name|cfg_scale/i.test(value)
          ? 'production'
          : /exif|gps|iptc/i.test(record.kind) ||
              /\b(?:copyright|creator|author|location|serialnumber|gps)\b/i.test(value)
            ? 'privacy'
            : 'other';
    fields.push({ id: `record-${record.id}`, label: record.kind, value, category, ai, record });
  }
  const structural = 'footprints' in scan ? scan.footprints : undefined;
  const textDeclarations = scan.records.filter(record =>
    structural
      ? structural.evidence.some(e => e.recordId === record.id && e.category === 'explicit-ai')
      : record.kind === 'XMP' && explicitTextDeclaration(record.preview),
  );
  const c2paSources = scan.provenance?.manifests.flatMap(manifest => manifest.aiSources) ?? [];
  const declarationCount = textDeclarations.length + c2paSources.length;
  const aiState = declarationCount
    ? 'declared'
    : provenance || structural?.incomplete || structural?.state === 'METADATA_HINTS'
      ? 'uncertain'
      : 'not-found';
  return {
    fields,
    provenance,
    aiCount: fields.filter(field => field.ai && field.record).length,
    declarationCount,
    aiState,
    textDeclarations,
    c2paSources,
    sectionCount: categories.filter(category => fields.some(field => field.category === category.id)).length,
  };
}
